const dict = { tr, en } as const;
export type Key = keyof typeof tr;

export const I18nContext = createContext<{ lang: Lang; setLang: (l: Lang) => void }>({
  lang: "tr",
  setLang: () => {},
});

export function useI18n() {
  const { lang, setLang } = useContext(I18nContext);
  const t = (k: Key, vars?: Record<string, string | number>) => {
    let s: string = dict[lang][k] ?? dict.tr[k] ?? k;
    if (vars) for (const [key, val] of Object.entries(vars)) s = s.replaceAll(`{${key}}`, String(val));
    return s;
  };
  return { lang, setLang, t };
}
